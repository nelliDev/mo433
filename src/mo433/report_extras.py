"""``mo433 report-extras``: tables, figures and macros for the post-freeze extra experiments.

Reads only committed CSVs (no GPU, no torch), like ``mo433 report``:

- ``results.csv`` (STL-10 main study) and ``report/eurosat/results.csv`` (EuroSAT main study);
- ``report/extras/{long300,sizes,lejepa}.csv`` and ``report/eurosat/extras/lejepa.csv``;
- ``report/extras/long300_curves.csv``.

Writes ``report/generated/extras_*.tex`` (tables and ``extras_macros.tex``, macros prefixed
``Ext``) and ``report/figures/extras_*.pdf``. Missing inputs give ``--`` cells and skipped
figures with a warning, so ``main.tex`` compiles while runs are still going.
"""

from __future__ import annotations

import math
import warnings
from collections import defaultdict
from pathlib import Path

import numpy as np

from mo433 import paths, report, report_figures, report_tex
from mo433.report_tex import FRAC_CODE, MISSING, PROBE_CODE, gap_cell, pct, pm, signed_pp

PROBE = "linear_svm"  # the brief's main probe (label-efficiency curve)
LFS = (1, 10, 100)
# Parameter counts of the student family (tests/test_report_extras.py checks them against
# students.build_student; hardcoded so this module never imports torch).
PARAMS = {"XS": 394_380, "S": 1_573_272, "M": 3_154_962, "L": 6_284_592}
SIZE_ORDER = ("XS", "S", "M", "L")
SIZE_CODE = {"XS": "XS", "S": "S", "M": "M", "L": "L"}
ROW_LABEL = {"A": "A (random init)", "B": "B (VICReg)", "J": "J (LeJEPA)", "C": "C (distilled)", "D": "D (teacher)"}
ROW_COLOR = {**report_figures.ROW_COLOR, "J": "#009E73"}
ROW_MARKER = {**report_figures.ROW_MARKER, "J": "^"}
DATASETS = {"stl10": "STL-10", "eurosat": "EuroSAT"}
DATA_MACRO = {"stl10": "Stl", "eurosat": "Eurosat"}


class Inputs:
    def __init__(self, repo: Path = paths.REPO_ROOT):
        r = Path(repo) / "report"
        self.repo = Path(repo)
        self.main = {"stl10": Path(repo) / "results.csv", "eurosat": r / "eurosat" / "results.csv"}
        self.lejepa = {"stl10": r / "extras" / "lejepa.csv", "eurosat": r / "eurosat" / "extras" / "lejepa.csv"}
        self.long300 = r / "extras" / "long300.csv"
        self.long300_curves = r / "extras" / "long300_curves.csv"
        self.sizes = r / "extras" / "sizes.csv"
        self.out = r


def _rows(path: Path, seeds: tuple[int, ...] | None = None) -> list[dict]:
    if not path.exists():
        warnings.warn(f"report-extras: {path} missing; its cells stay '{MISSING}'")
        return []
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # the fixed-view control ids (…-fv-otf) are not in these tables
        rows = [r for r in report.read_results(path) if r["feature_set"] == "main"]
    if seeds is not None:
        rows = [r for r in rows if report.parse_encoder(r["encoder_id"]).seed in seeds or r["encoder_id"] == "D"]
    return rows


def _gap(cells, b_group: str, x_group: str, lf: int):
    """``x - b`` as a report.Gap-like object (gap, ref_sd, beyond) or None."""
    b, x = cells.get((b_group, PROBE, lf)), cells.get((x_group, PROBE, lf))
    if b is None or x is None:
        return None
    ref = max(b.sd, x.sd) if not (math.isnan(b.sd) or math.isnan(x.sd)) else float("nan")
    gap = x.mean - b.mean
    return report.Gap("", 0, PROBE, lf, gap, ref, bool(not math.isnan(ref) and abs(gap) > ref))


class Macros:
    def __init__(self):
        self.items: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        assert name.isalpha(), name
        self.items["Ext" + name] = value

    def acc(self, name: str, cell) -> None:
        self.add(f"Acc{name}", pct(cell.mean) if cell else report_tex.MISSING_MACRO)
        self.add(f"AccSd{name}", pct(cell.sd) if cell and not math.isnan(cell.sd) else report_tex.MISSING_MACRO)

    def gap(self, name: str, g) -> None:
        self.add(f"Gap{name}", signed_pp(g.gap) if g else report_tex.MISSING_MACRO)
        self.add(f"GapSd{name}", pct(g.ref_sd) if g and not math.isnan(g.ref_sd) else report_tex.MISSING_MACRO)

    def render(self) -> str:
        lines = ["% Generated by `mo433 report-extras`. Do not edit."]
        lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in self.items.items()]
        return "\n".join(lines) + "\n"


def _table(caption, label, colspec, header, body, notes) -> str:
    out = report_tex._table(caption, label, colspec, header, body, notes)
    return out.replace("Generated by `mo433 report`", "Generated by `mo433 report-extras`")


def _cmid(table: str, rule: str) -> str:
    """Two-level header: the first midrule (under the group header) becomes cmidrules."""
    return table.replace("\\midrule\n", rule + "\n", 1)


GAP_NOTE = (r"Gaps in percentage points with max(sd) in parentheses; $^*$ = larger than the "
            r"seed-to-seed spread.")


# ---------------------------------------------------------------- datasets x direct objective


def datasets_cells(inp: Inputs) -> dict[str, dict]:
    out = {}
    for ds in DATASETS:
        rows = _rows(inp.main[ds]) + _rows(inp.lejepa[ds])
        out[ds] = report.aggregate(rows)
    return out


DATASET_GROUPS = ("A-S", "B-S-100", "J-S-100", "C-S-100", "D")


def datasets_table(cells: dict[str, dict], m: Macros) -> str:
    body = []
    for group in DATASET_GROUPS:
        row = report.parse_group(group).row
        line = [ROW_LABEL[row]]
        for ds in DATASETS:
            for lf in LFS:
                c = cells[ds].get((group, PROBE, lf))
                line.append(pm(c))
                m.acc(f"{DATA_MACRO[ds]}{row}{FRAC_CODE[lf]}", c)
        body.append(" & ".join(line) + r" \\")
    body.append(r"\midrule")
    for x, label in (("C-S-100", r"$\Delta$ C$-$B"), ("J-S-100", r"$\Delta$ J$-$B"), ("C-S-100", r"$\Delta$ C$-$J")):
        base = "J-S-100" if label.endswith("J") else "B-S-100"
        line = [label]
        for ds in DATASETS:
            for lf in LFS:
                g = _gap(cells[ds], base, x, lf)
                line.append(gap_cell(g))
                code = label.replace(r"$\Delta$ ", "").replace("$-$", "Minus")
                m.gap(f"{DATA_MACRO[ds]}{code}{FRAC_CODE[lf]}", g)
        body.append(" & ".join(line) + r" \\")
    header = ["S student"] + [f"{lf}\\%" for lf in LFS] * 2
    out = _table(
        "Linear-SVM test accuracy (\\%) on STL-10 and EuroSAT with three direct or distilled objectives for "
        "the S student (100\\% unlabeled data, frozen settings). B and C: 3 seeds; J (LeJEPA, extra "
        "experiment): 2 seeds; D: sd over label draws.",
        "tab:extras-datasets", "l" + "c" * 6,
        [r"\multicolumn{1}{l}{}", r"\multicolumn{3}{c}{STL-10}", r"\multicolumn{3}{c}{EuroSAT}"],
        [" & ".join(header) + r" \\", r"\midrule"] + body, [GAP_NOTE],
    )
    return _cmid(out, r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}")


def label_efficiency_figure(cells: dict[str, dict], path: Path) -> Path | None:
    if not any(cells[ds] for ds in DATASETS):
        return None
    plt = report_figures._plt()
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6), sharey=False)
    for ax, ds in zip(axes, DATASETS):
        for group in DATASET_GROUPS:
            row = report.parse_group(group).row
            pts = [(lf, cells[ds].get((group, PROBE, lf))) for lf in report.LABEL_FRACS]
            pts = [(lf, c) for lf, c in pts if c is not None]
            if not pts:
                continue
            x = [lf for lf, _ in pts]
            y = np.array([100 * c.mean for _, c in pts])
            sd = np.array([100 * report_figures._nan_to_zero(c.sd) for _, c in pts])
            ax.plot(x, y, marker=ROW_MARKER[row], color=ROW_COLOR[row], label=ROW_LABEL[row], markersize=4)
            ax.fill_between(x, y - sd, y + sd, color=ROW_COLOR[row], alpha=0.15, linewidth=0)
        ax.set_xscale("log")
        ax.set_xticks(report.LABEL_FRACS, [f"{lf}%" for lf in report.LABEL_FRACS])
        ax.set_xlabel("labeled fraction")
        ax.set_title(DATASETS[ds])
    axes[0].set_ylabel("linear-SVM test accuracy (%)")
    handles, labels = axes[1].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=len(labels), fontsize=7, bbox_to_anchor=(0.5, -0.16))
    return report_figures._save(fig, path)


# ---------------------------------------------------------------- longer training


def long300_cells(inp: Inputs) -> tuple[dict, dict]:
    """(E=100 cells from the main study restricted to seeds 0-1, E=300 cells)."""
    return report.aggregate(_rows(inp.main["stl10"], seeds=(0, 1))), report.aggregate(_rows(inp.long300))


def long300_table(c100: dict, c300: dict, m: Macros) -> str:
    body = []
    for row in ("B", "C"):
        for e, cells in ((100, c100), (300, c300)):
            line = [f"{ROW_LABEL[row]}, $E={e}$"]
            for lf in report.LABEL_FRACS:
                c = cells.get((f"{row}-S-100", PROBE, lf))
                line.append(pm(c))
                m.acc(f"Long{row}E{'Hundred' if e == 100 else 'ThreeHundred'}{FRAC_CODE[lf]}", c)
            body.append(" & ".join(line) + r" \\")
    body.append(r"\midrule")
    for e, cells in ((100, c100), (300, c300)):
        line = [rf"$\Delta$ C$-$B, $E={e}$"]
        for lf in report.LABEL_FRACS:
            g = _gap(cells, "B-S-100", "C-S-100", lf)
            line.append(gap_cell(g))
            m.gap(f"LongE{'Hundred' if e == 100 else 'ThreeHundred'}{FRAC_CODE[lf]}", g)
        body.append(" & ".join(line) + r" \\")
    return _table(
        "Longer training (extra experiment): linear-SVM test accuracy (\\%) of the S student at $E=100$ "
        "(main study, seeds 0--1 only) and $E=300$ (seeds 0--1), 100\\% unlabeled data, STL-10.",
        "tab:extras-long300", "lcccc", ["Encoder"] + [f"{lf}\\%" for lf in report.LABEL_FRACS], body, [GAP_NOTE],
    )


def long300_curves_figure(inp: Inputs, path: Path) -> Path | None:
    if not inp.long300_curves.exists():
        warnings.warn(f"report-extras: {inp.long300_curves} missing; no curve figure")
        return None
    series: dict[tuple[str, int], dict[int, list[float]]] = defaultdict(lambda: defaultdict(list))
    for r in report._read_csv(inp.long300_curves):
        if r.get("val_knn") in (None, ""):
            continue
        row = report.parse_encoder(r["run_id"]).row
        series[(row, int(r["epochs"]))][int(r["epoch"])].append(100 * float(r["val_knn"]))
    plt = report_figures._plt()
    fig, ax = plt.subplots(figsize=(3.6, 2.6))
    for (row, e), by_epoch in sorted(series.items()):
        x = sorted(by_epoch)
        y = [np.mean(by_epoch[k]) for k in x]
        ax.plot(x, y, color=ROW_COLOR[row], linestyle="-" if e == 300 else "--", linewidth=1.2,
                label=f"{ROW_LABEL[row]}, E={e}")
    ax.set_xlabel("epoch")
    ax.set_ylabel("validation $k$-NN accuracy (%)")
    ax.legend(fontsize=7, loc="lower right")
    return report_figures._save(fig, path)


# ---------------------------------------------------------------- student sizes


def sizes_cells(inp: Inputs) -> dict:
    """S and L from the main study (all seeds), XS and M from the sizes study."""
    return report.aggregate(_rows(inp.main["stl10"]) + _rows(inp.sizes))


def sizes_table(cells: dict, m: Macros) -> str:
    body = []
    for size in SIZE_ORDER:
        line = [size, f"{PARAMS[size] / 1e6:.2f}"]
        for lf in LFS:
            b, c = cells.get((f"B-{size}-100", PROBE, lf)), cells.get((f"C-{size}-100", PROBE, lf))
            g = _gap(cells, f"B-{size}-100", f"C-{size}-100", lf)
            line += [pct(b.mean) if b else MISSING, pct(c.mean) if c else MISSING, gap_cell(g)]
            m.acc(f"SizeB{SIZE_CODE[size]}{FRAC_CODE[lf]}", b)
            m.acc(f"SizeC{SIZE_CODE[size]}{FRAC_CODE[lf]}", c)
            m.gap(f"Size{SIZE_CODE[size]}{FRAC_CODE[lf]}", g)
        body.append(" & ".join(line) + r" \\")
    for size in SIZE_ORDER:
        m.add(f"Params{SIZE_CODE[size]}", f"{PARAMS[size] / 1e6:.2f}")
    sub = " & ".join([r"\multicolumn{1}{l}{}"] * 2 + [rf"\multicolumn{{3}}{{c}}{{{lf}\% labels}}" for lf in LFS]) + r" \\"
    head = ["Size", "Params (M)"] + ["B", "C", r"$\Delta$"] * len(LFS)
    out = _table(
        "Four student sizes (XS and M are extra experiments): linear-SVM test accuracy (\\%) on STL-10, "
        "100\\% unlabeled data, $E=100$. XS, M and L: 2 seeds; S: 3 seeds. Widths 12/24/34/48, same "
        "scaling rule.",
        "tab:extras-sizes", "lr" + "ccc" * len(LFS), [sub.removesuffix(r" \\")], [" & ".join(head) + r" \\", r"\midrule"] + body,
        [GAP_NOTE],
    )
    return _cmid(out, r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}\cmidrule(lr){9-11}")


def sizes_figure(cells: dict, path: Path) -> Path | None:
    if not cells:
        return None
    plt = report_figures._plt()
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.0, 2.6))
    for row in ("B", "C"):
        pts = [(PARAMS[s], cells.get((f"{row}-{s}-100", PROBE, 10))) for s in SIZE_ORDER]
        pts = [(p, c) for p, c in pts if c is not None]
        if pts:
            ax1.errorbar([p / 1e6 for p, _ in pts], [100 * c.mean for _, c in pts],
                         yerr=[100 * report_figures._nan_to_zero(c.sd) for _, c in pts], marker=ROW_MARKER[row],
                         color=ROW_COLOR[row], label=ROW_LABEL[row], capsize=2, markersize=4)
    d = cells.get(("D", PROBE, 10))
    if d is not None:
        ax1.axhline(100 * d.mean, color=ROW_COLOR["D"], linestyle=":", linewidth=1, label="D (teacher, 21.7M)")
    ax1.set_xscale("log")
    ax1.set_xlabel("student parameters (M)")
    ax1.set_ylabel("linear-SVM accuracy, 10% labels (%)")
    ax1.legend(fontsize=7, loc="lower right")
    for lf in LFS:
        pts = [(PARAMS[s], _gap(cells, f"B-{s}-100", f"C-{s}-100", lf)) for s in SIZE_ORDER]
        pts = [(p, g) for p, g in pts if g is not None]
        if pts:
            ax2.errorbar([p / 1e6 for p, _ in pts], [100 * g.gap for _, g in pts],
                         yerr=[100 * report_figures._nan_to_zero(g.ref_sd) for _, g in pts], marker="o",
                         color=report_figures.FRAC_COLOR[lf], label=f"{lf}% labels", capsize=2, markersize=4)
    ax2.axhline(0, color="#999999", linewidth=0.8)
    ax2.set_xscale("log")
    ax2.set_xlabel("student parameters (M)")
    ax2.set_ylabel("gap C $-$ B (pp)")
    ax2.legend(fontsize=7)
    for ax in (ax1, ax2):
        ax.set_xticks([PARAMS[s] / 1e6 for s in SIZE_ORDER], [f"{s}\n{PARAMS[s] / 1e6:.1f}" for s in SIZE_ORDER])
        ax.minorticks_off()
    return report_figures._save(fig, path)


# ---------------------------------------------------------------- entry point


def build(inp: Inputs | None = None, log=print) -> list[Path]:
    inp = inp or Inputs()
    gen, figs = inp.out / "generated", inp.out / "figures"
    gen.mkdir(parents=True, exist_ok=True)
    figs.mkdir(parents=True, exist_ok=True)
    m = Macros()
    written = []

    ds = datasets_cells(inp)
    c100, c300 = long300_cells(inp)
    sz = sizes_cells(inp)
    tables = {
        "extras_datasets": datasets_table(ds, m),
        "extras_long300": long300_table(c100, c300, m),
        "extras_sizes": sizes_table(sz, m),
    }
    for name, text in tables.items():
        p = gen / f"{name}.tex"
        p.write_text(text)
        written.append(p)
    p = gen / "extras_macros.tex"
    p.write_text(m.render())
    written.append(p)

    for name, fn in (("extras_label_efficiency", lambda q: label_efficiency_figure(ds, q)),
                     ("extras_long300_curves", lambda q: long300_curves_figure(inp, q)),
                     ("extras_sizes", lambda q: sizes_figure(sz, q))):
        out = fn(figs / f"{name}.pdf")
        if out is not None:
            written.append(out)
    log(f"report-extras: wrote {len(written)} files under {inp.out}")
    return written
